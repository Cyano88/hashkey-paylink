import assert from 'node:assert/strict'
import {readFileSync} from 'node:fs'
const {chromium}=await import(process.env.PLAYWRIGHT_MODULE??'file:///C:/Users/USER/AppData/Local/npm-cache/_npx/31e32ef8478fbf80/node_modules/playwright/index.mjs')
const browser=await chromium.launch({headless:true,channel:'chrome'})
const html=readFileSync('output/playwright/arc-trade-fixture.html','utf8')
async function open(scenario='pending'){
 const page=await browser.newPage({viewport:{width:390,height:844}})
 await page.route('**/*',r=>r.fulfill({body:html,contentType:'text/html'}))
 await page.clock.install()
 await page.goto('https://fixture.invalid/?scenario='+scenario)
 await page.clock.runFor(300)
 await page.getByRole('button',{name:'Connect Arc wallet',exact:true}).click()
 await page.clock.runFor(500)
 return page
}
try{
 const pending=await open()
 assert.equal(await pending.getByRole('button',{name:'Check action status',exact:true}).count(),0)
 assert.equal(await pending.getByRole('button',{name:'Refresh agreement',exact:true}).count(),0)
 await pending.getByRole('button',{name:'Checking...',exact:true}).waitFor()
 await pending.clock.runFor(17000)
 await pending.getByText('Payment held',{exact:true}).waitFor()
 assert.equal(await pending.evaluate(()=>window.fixture.executions.length),0,'Recovery must never sign')
 assert.equal(await pending.getByRole('button',{name:'Checking...',exact:true}).count(),0)
 await pending.close()

 const submit=await open('buyer')
 await submit.getByRole('button',{name:'Approve payment',exact:true}).click()
 await submit.getByRole('button',{name:'Continue to wallet confirmation',exact:true}).click()
 await submit.clock.runFor(18000)
 await submit.getByText('Payment held',{exact:true}).waitFor()
 assert.equal(await submit.evaluate(()=>window.fixture.executions.length),1,'One explicit confirmation only')
 assert.equal(await submit.evaluate(()=>window.fixture.calls.filter(c=>c.action==='challenge').length),1)
 await submit.close()

 const outage=await open()
 await outage.evaluate(()=>window.fixture.failures=3)
 await outage.clock.runFor(40000)
 await outage.getByRole('button',{name:'Try again',exact:true}).waitFor()
 const stopped=await outage.evaluate(()=>window.fixture.calls.length)
 await outage.clock.runFor(60000)
 assert.equal(await outage.evaluate(()=>window.fixture.calls.length),stopped,'Repeated failures must stop polling')
 await outage.getByRole('button',{name:'Try again',exact:true}).click()
 await outage.clock.runFor(1000)
 await outage.getByText('Payment held',{exact:true}).waitFor()
 assert.equal(await outage.evaluate(()=>window.fixture.executions.length),0)
 await outage.close()

 const stalled=await open()
 await stalled.evaluate(()=>window.fixture.stall=true)
 await stalled.clock.runFor(96000)
 await stalled.getByRole('button',{name:'Continue wallet confirmation',exact:true}).waitFor()
 assert.equal(await stalled.evaluate(()=>window.fixture.executions.length),0)
 await stalled.getByRole('button',{name:'Continue wallet confirmation',exact:true}).click()
 await stalled.clock.runFor(1500)
 assert.equal(await stalled.evaluate(()=>window.fixture.executions.length),1)
 const requestIds=await stalled.evaluate(()=>window.fixture.calls.filter(c=>['recover','challenge'].includes(c.action)).map(c=>c.requestId))
 assert.equal(new Set(requestIds).size,1,'Explicit resume must retain the original request')
 await stalled.close()

 const idle=await open('buyer')
 await idle.clock.runFor(3000)
 await idle.evaluate(()=>Object.defineProperty(document,'hidden',{configurable:true,value:true}))
 const hiddenCalls=await idle.evaluate(()=>window.fixture.calls.length)
 await idle.clock.runFor(30000)
 assert.equal(await idle.evaluate(()=>window.fixture.calls.length),hiddenCalls)
 await idle.evaluate(()=>{Object.defineProperty(document,'hidden',{configurable:true,value:false});Object.defineProperty(navigator,'onLine',{configurable:true,value:false});document.dispatchEvent(new Event('visibilitychange'))})
 await idle.clock.runFor(30000)
 assert.equal(await idle.evaluate(()=>window.fixture.calls.length),hiddenCalls)
 await idle.evaluate(()=>{window.fixture.state=2;Object.defineProperty(navigator,'onLine',{configurable:true,value:true});window.dispatchEvent(new Event('online'))})
 await idle.clock.runFor(1500)
 await idle.getByText('Payment held',{exact:true}).waitFor()
 await idle.screenshot({path:'output/playwright/arc-trade-auto-status.png'})
 await idle.close()
 console.log('PASS automatic confirmation, single explicit signing, bounded outage retries, hidden/offline pause and counterparty state refresh')
}finally{await browser.close()}
