import assert from 'node:assert/strict'
import {createXPayBankStore} from '../api/pocket/xpay-bank-store.ts'
const db=new Map();let seq=0
const store=createXPayBankStore({read:async k=>structuredClone(db.get(k)),mutate:async(k,fn)=>{const next=await fn(structuredClone(db.get(k)));db.set(k,structuredClone(next));return next},now:()=>1000,id:()=>String(++seq)})
const source='0x'+'1'.repeat(40),token='0x'+'2'.repeat(40),output='0x'+'3'.repeat(40),hash='0x'+'a'.repeat(64)
const quote={owner:source,tokenIn:{address:token},tokenOut:{address:output},amountUnits:'500',minimumOutUnits:'101',decimalsIn:18,decimalsOut:6,expiresAt:3000,chainId:196,gasFee:'0.001'}
const input={owner:'alice',key:'one',checkoutId:'qr',merchantId:'merchant',source,token,symbol:'TEST',amount:'0.5',amountUnits:'500',fiatAmount:'1000',payout:{intentId:'original',merchantId:'merchant',wallet:source,walletId:'wallet',fiatAmount:'1000',currency:'NGN',fundingUnits:'100',expiresAt:1000000},bridgeId:'bridge',bridgeUnits:'101',swap:quote}
const r=await store.create(input),other=await store.create({...input,key:'two'})
assert.equal((await store.create(input)).id,r.id)
await assert.rejects(()=>store.create({...input,fiatAmount:'2000'}))
await assert.rejects(()=>store.approve('bob',r.id))
await store.approve('alice',r.id)
await assert.rejects(()=>store.approve('alice',other.id))
await assert.rejects(()=>store.startBridge('alice',r.id))
for(const patch of [{minimumOutUnits:'100'},{amountUnits:'501'},{tokenOut:{address:source}},{gasFee:'0.002'},{expiresAt:999}])await assert.rejects(()=>store.startSwap('alice',r.id,{...quote,...patch},'10'))
await store.startSwap('alice',r.id,quote,'10')
await assert.rejects(()=>store.retrySwap('alice',r.id))
await assert.rejects(()=>store.verifiedFailure('alice',r.id,'swap',hash,'timeout'))
await store.swapSubmitted('alice',r.id,hash)
await assert.rejects(()=>store.swapSubmitted('alice',r.id,'0x'+'b'.repeat(64)))
await assert.rejects(()=>store.verifiedFailure('alice',r.id,'swap','other','reverted'))
await store.verifiedFailure('alice',r.id,'swap',hash,'reverted')
await assert.rejects(()=>store.approve('alice',other.id))
await assert.rejects(()=>store.retryPayment('alice',r.id))
await store.retrySwap('alice',r.id)
await store.startSwap('alice',r.id,quote,'20');await store.swapSubmitted('alice',r.id,hash)
await store.swapConfirmed('alice',r.id,'102');await store.startBridge('alice',r.id)
await store.verifiedFailure('alice',r.id,'bridge','bridge','source reverted');await store.retryBridge('alice',r.id,'new-bridge')
assert.equal((await store.find('alice',r.id)).swapHash,hash)
await assert.rejects(()=>store.startSwap('alice',r.id,quote,'30'))
await store.bridgeConfirmed('alice',r.id)
const updated={...input.payout,intentId:'replacement',fundingUnits:'99'}
await assert.rejects(()=>store.offerPayout('alice',r.id,{...updated,fundingUnits:'101'}))
await store.offerPayout('alice',r.id,updated)
await assert.rejects(()=>store.claimPayout('alice',r.id))
await assert.rejects(()=>store.acceptPayout('alice',r.id,'other'))
await store.acceptPayout('alice',r.id,'replacement')
assert.equal((await store.find('alice',r.id)).previousPayouts[0].intentId,'original')
const claimed=await store.claimPayout('alice',r.id)
await assert.rejects(()=>store.offerPayout('alice',r.id,updated))
assert.equal((await store.claimPayout('alice',r.id)).payoutKey,claimed.payoutKey)
await assert.rejects(()=>store.retryPayment('alice',r.id))
await store.payoutChallenge('alice',r.id,claimed.payoutKey,'challenge')
await assert.rejects(()=>store.complete('alice',other.id,hash))
await store.verifiedFailure('alice',r.id,'payment','challenge','provider failed');await store.retryPayment('alice',r.id)
const retry=await store.claimPayout('alice',r.id);assert.notEqual(retry.payoutKey,claimed.payoutKey)
await assert.rejects(()=>store.payoutChallenge('alice',r.id,claimed.payoutKey,'old'))
await store.payoutChallenge('alice',r.id,retry.payoutKey,'new')
await store.complete('alice',r.id,hash)
await assert.rejects(()=>store.verifiedFailure('alice',r.id,'payment','new','late failure'))
await assert.rejects(()=>store.complete('alice',r.id,'0x'+'c'.repeat(64)))
await assert.rejects(()=>store.delivery('alice',r.id,'0x'+'f'.repeat(64),'refunded'))
await store.delivery('alice',r.id,hash,'refunding')
assert.equal((await store.find('alice',r.id)).state,'successful')
await store.delivery('alice',r.id,hash,'refunded')
await store.delivery('alice',r.id,hash,'settled')
assert.equal((await store.find('alice',r.id)).state,'refunded')
assert.equal((await store.find('alice',r.id)).bankDelivery,'refunded')
console.log('PASS XPay bank journal: owner isolation, serial approval, quote limits, unknown-outcome retry rejection, stage-only recovery, immutable submissions and terminal success.')
