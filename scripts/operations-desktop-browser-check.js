async page => {
  const check = (condition, message) => { if (!condition) throw Error(message) }
  await page.goto('http://127.0.0.1:4321/admin/workspaces/hashpaystream')
  await page.getByRole('heading', { name: 'Hash PayStream', exact: true }).waitFor()
  await page.evaluate(() => document.fonts.ready)
  await page.getByRole('button', { name: 'Open navigation' }).click()
  check(await page.getByRole('button', { name: 'Sign out', exact: true }).count() === 1, 'Duplicate sign out')
  await page.getByRole('button', { name: 'Close navigation' }).click()
  await page.screenshot({ path: 'output/playwright/operations-workspace-desktop.png' })
  const nav = page.getByRole('navigation', { name: 'Workspace sections' })
  await nav.getByRole('link', { name: 'Arc agreements', exact: true }).click()
  await page.getByText('No Arc Agreements recorded.', { exact: true }).waitFor()
  await page.getByText('Activation settings', { exact: false }).click()
  await page.getByText('Project approved', { exact: true }).waitFor()
  check(await page.getByText('Platform paused', { exact: true }).count() === 1, 'Missing distinct runtime state')
  const calls = await page.evaluate(() => window.__requests.filter(r => ['/api/developer-projects', '/api/arc-agreement-operations'].includes(r.path)))
  check(calls.length > 1 && calls.every(r => r.workspace === 'hashpaystream'), 'Missing workspace query')
  await nav.getByRole('link', { name: 'Escalations', exact: true }).click()
  await page.getByRole('heading', { name: 'Escalation connection not configured' }).waitFor()
  check(await page.getByRole('textbox').count() === 0, 'Unexpected customer inbox')
  await page.getByRole('button', { name: 'Open navigation' }).click()
  await page.getByRole('navigation', { name: 'Product workspaces' }).getByRole('link', { name: 'Pocket', exact: true }).click()
  check(await nav.getByRole('link', { name: 'Trade disputes' }).count() === 0, 'Pocket has unrelated dispute tools')
  await nav.getByRole('link', { name: 'Support inbox' }).click()
  await page.waitForFunction(() => window.__requests.some(r => r.path === '/api/pocket/support/cases' && r.workspace === 'pocket'))
  await page.goto('http://127.0.0.1:4321/admin/workspaces/hashpaystream/projects?limited')
  await page.getByRole('heading', { name: 'Workspace unavailable' }).waitFor()
  check(await page.evaluate(() => window.__requests.every(r => r.path === '/api/operations-session')), 'Denied page loaded protected data')
  check(await page.getByRole('navigation', { name: 'Workspace sections' }).getByRole('link', { name: 'Integrations', exact: true }).count() === 0, 'Restricted section visible')
  await page.goto('http://127.0.0.1:4321/admin?denied')
  await page.getByRole('alert').waitFor()
  check(await page.getByRole('combobox').count() === 0, 'Unauthorized product list')
  await page.setViewportSize({ width: 390, height: 844 })
  await page.goto('http://127.0.0.1:4321/admin/workspaces/hashpaystream')
  await page.getByRole('heading', { name: 'Hash PayStream', exact: true }).waitFor()
  check(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), 'Mobile page overflow')
  await page.screenshot({ path: 'output/playwright/operations-workspace-mobile.png' })
  await page.setViewportSize({ width: 1440, height: 1000 })
  await page.evaluate(() => document.documentElement.classList.add('dark'))
  check(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), 'Desktop page overflow')
  await page.screenshot({ path: 'output/playwright/operations-workspace-dark.png' })
  return 'PASS: scoped navigation and requests, one sign-out, runtime/approval distinction, escalation honesty, denied routes do not fetch protected data, and responsive light/dark layouts.'
}
