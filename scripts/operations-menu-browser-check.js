async page => {
 const check=(value,message)=>{if(!value)throw Error(message)}
 await page.setViewportSize({width:1440,height:1000})
 await page.goto('http://127.0.0.1:4322/admin/workspaces/hashpaystream')
 const trigger=page.getByRole('button',{name:'Open navigation',exact:true})
 await trigger.waitFor()
 check(!await page.getByRole('dialog',{name:'Operations menu'}).isVisible(),'Menu must start hidden')
 await page.screenshot({path:'output/playwright/operations-menu-closed.png'})
 await trigger.click()
 const dialog=page.getByRole('dialog',{name:'Operations menu'})
 await dialog.waitFor()
 check(await trigger.getAttribute('aria-expanded')==='true','Menu state missing')
 await page.screenshot({path:'output/playwright/operations-menu-open.png'})
 await page.keyboard.press('Escape')
 check(!await dialog.isVisible(),'Escape must close menu')
 check(await trigger.evaluate(el=>el===document.activeElement),'Focus must return to menu button')
 await page.getByRole('navigation',{name:'Workspace sections'}).getByRole('link',{name:'Trade disputes',exact:true}).click()
 await page.getByText('Sample delivery dispute',{exact:true}).waitFor()
 check(!await dialog.isVisible(),'Section navigation must close menu')
 await trigger.click()
 await dialog.getByRole('navigation',{name:'Product workspaces'}).getByRole('link',{name:'Pocket',exact:true}).click()
 await page.getByRole('heading',{name:'Pocket',exact:true}).waitFor()
 check(!await dialog.isVisible(),'Product selection must close menu')
 await page.setViewportSize({width:390,height:844})
 await trigger.click()
 check(await dialog.isVisible(),'Mobile menu missing')
 check(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth),'Mobile overflow')
 await page.screenshot({path:'output/playwright/operations-menu-mobile.png'})
 await dialog.getByRole('button',{name:'Close navigation'}).click()
 check(!await dialog.isVisible(),'Close button must close menu')
 await page.setViewportSize({width:1440,height:1000})
 const toDark=page.getByRole('button',{name:'Switch to dark theme'})
 if(await toDark.count())await toDark.click()
 check(await page.evaluate(()=>document.documentElement.classList.contains('dark')),'Dark theme not applied')
 await page.reload()
 await trigger.waitFor()
 check(await page.evaluate(()=>document.documentElement.classList.contains('dark')),'Theme not retained after reload')
 await page.screenshot({path:'output/playwright/operations-reference-dark.png'})
 await page.getByRole('button',{name:'Switch to light theme'}).click()
 check(await page.evaluate(()=>!document.documentElement.classList.contains('dark')),'Light theme not applied')
 await page.screenshot({path:'output/playwright/operations-reference-light.png'})
 check(await trigger.evaluate(el=>!!el.closest('header')),'Menu must be in top header')
 await trigger.click()
 await page.screenshot({path:'output/playwright/operations-reference-drawer.png'})
 return 'PASS: hidden by default, desktop/mobile drawer, Escape and focus return, section and workspace navigation close drawer.'
}
