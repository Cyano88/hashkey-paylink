import assert from 'node:assert/strict'
import {createXPayBridgeJournal} from '../api/pocket/xpay-bridge-journal.ts'
const stores=new Map();let n=0
const journal=createXPayBridgeJournal({read:async k=>structuredClone(stores.get(k)),mutate:async(k,fn)=>{const next=await fn(structuredClone(stores.get(k)));stores.set(k,structuredClone(next));return next},now:()=>1000,id:()=>String(++n)})
const plan={source:'source',destination:'base',minimumReceiveUnits:'100',burnUnits:'101',maxFeeUnits:'1',finality:1000,expiresAt:2000}
const r=await journal.create('alice','key','qr',plan)
assert.equal((await journal.create('alice','key','qr',plan)).id,r.id)
await assert.rejects(()=>journal.create('alice','key','qr',{...plan,minimumReceiveUnits:'200'}))
await assert.rejects(()=>journal.claimBurn('bob',r.id,'10'))
const second=await journal.create('alice','second-quote','qr',plan)
await assert.rejects(()=>journal.refreshQuote('alice',r.id,{...plan,burnUnits:'102',maxFeeUnits:'2'}))
await assert.rejects(()=>journal.refreshQuote('alice',r.id,{...plan,destination:'other'}))
await journal.refreshQuote('alice',r.id,{...plan,expiresAt:3000})
await journal.claimBurn('alice',r.id,'10');await assert.rejects(()=>journal.claimBurn('alice',second.id,'10'));
await assert.rejects(()=>journal.claimBurn('alice',r.id,'10'))
await assert.rejects(()=>journal.create('alice','another','qr',plan))
const hash='0x'+'1'.repeat(64);await journal.recordBurnHash('alice',r.id,hash)
await assert.rejects(()=>journal.refreshQuote('alice',r.id,{...plan,expiresAt:4000}))
await assert.rejects(()=>journal.recordBurnHash('alice',r.id,'0x'+'2'.repeat(64)))
assert.equal((await journal.pending('alice'))[0].state,'burn_submitted')
const proof={message:'verified message',attestation:'verified signature',nonce:'nonce'}
await journal.recordAttestation('alice',r.id,proof)
const mint=await journal.claimMint('alice',r.id)
assert.equal((await journal.claimMint('alice',r.id)).mintKey,mint.mintKey)
await assert.rejects(()=>journal.recordChallenge('alice',r.id,mint.mintKey,'challenge'))
await journal.validateMint('alice',r.id,mint.mintKey)
await journal.recordChallenge('alice',r.id,mint.mintKey,'challenge')
await journal.markMintFailed('alice',r.id,mint.mintKey)
await assert.rejects(()=>journal.claimBurn('alice',r.id,'10'))
await assert.rejects(()=>journal.recordAttestation('alice',r.id,{...proof,nonce:'other'}))
await journal.recordAttestation('alice',r.id,proof)
const retry=await journal.claimMint('alice',r.id);assert.notEqual(retry.mintKey,mint.mintKey);assert.equal(retry.burnHash,hash)
await assert.rejects(()=>journal.recordChallenge('alice',r.id,mint.mintKey,'stale challenge'))
await journal.validateMint('alice',r.id,retry.mintKey)
await journal.recordChallenge('alice',r.id,retry.mintKey,'new challenge')
const destinationHash='0x'+'3'.repeat(64);await journal.complete('alice',r.id,destinationHash)
assert.equal((await journal.pending('alice')).length,0)
assert.equal((await journal.find('alice',r.id)).state,'completed')
await assert.rejects(()=>journal.markMintFailed('alice',r.id,retry.mintKey))
await assert.rejects(()=>journal.complete('alice',r.id,hash))
console.log('PASS durable bridge lifecycle: owner isolation, replay, one burn, immutable hashes, lost-response mint key, mint-only retry, stale challenge rejection and terminal success protection.')
