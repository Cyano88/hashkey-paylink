async page => {
 const check=(value,message)=>{if(!value)throw Error(message)}
 await page.goto('http://127.0.0.1:4321/admin/team')
 await page.getByRole('heading',{name:'Team access',exact:true}).waitFor()
 await page.getByLabel('Work email',{exact:true}).fill('staff@example.test')
 await page.getByLabel('Customer support',{exact:true}).check()
 await page.getByRole('button',{name:'Save access',exact:true}).click()
 await page.getByText('Access saved. The team member can sign in with this email.',{exact:true}).waitFor()
 check(await page.getByRole('button',{name:'Revoke',exact:true}).count()===1,'Grant not displayed')
 const writes=await page.evaluate(()=>window.__requests.filter(r=>r.path==='/api/operations-team'&&r.body).map(r=>JSON.parse(r.body)))
 check(writes.length===1&&writes[0].workspaceId==='pocket'&&writes[0].roles.join(',')==='support','Incorrect role assignment')
 await page.getByRole('combobox',{name:'Product',exact:true}).selectOption('hashpaystream')
 check(await page.getByLabel('Compliance',{exact:true}).count()===1,'Compliance unavailable for app review')
 check(await page.getByLabel('Customer support',{exact:true}).count()===0,'Unsupported role offered')
 check(await page.getByRole('button',{name:'Save access',exact:true}).isDisabled(),'Role selection leaked across products')
 await page.setViewportSize({width:390,height:844})
 check(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth),'Mobile overflow')
 await page.screenshot({path:'output/playwright/admin-team-mobile.png',fullPage:true})
 page.once('dialog',dialog=>dialog.accept())
 await page.getByRole('button',{name:'Revoke',exact:true}).click()
 await page.getByText('Access revoked for this workspace.',{exact:true}).waitFor()
 check(await page.getByRole('button',{name:'Revoke',exact:true}).count()===0,'Revoked access still listed')
 await page.goto('http://127.0.0.1:4321/admin/team?limited')
 await page.getByRole('alert').waitFor()
 check(await page.getByRole('textbox').count()===0,'Team controls exposed to non-owner')
 await page.goto('http://127.0.0.1:4321/admin/workspaces/pocket/transactions')
 await page.getByRole('button',{name:'Reconcile',exact:true}).waitFor()
 check(await page.getByRole('button',{name:'Reconcile',exact:true}).isDisabled(),'Reconcile offered without permission')
 console.log('PASS team assignment/revocation, product role reset, non-owner denial and mobile layout.')
}
