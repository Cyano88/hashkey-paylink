import assert from 'node:assert/strict'
import {readFileSync} from 'node:fs'
const {chromium}=await import(process.env.PLAYWRIGHT_MODULE??'file:///C:/Users/USER/AppData/Local/npm-cache/_npx/31e32ef8478fbf80/node_modules/playwright/index.mjs')
const browser=await chromium.launch({headless:true,channel:'chrome'})
try{
 const page=await browser.newPage()
 const html=readFileSync('output/playwright/arc-trade-fixture.html','utf8')
 await page.route('**/*',r=>r.fulfill({body:html,contentType:'text/html'}))
 await page.clock.install()
 const visit=async suffix=>{await page.goto('https://fixture.invalid/?scenario=buyer'+suffix);await page.clock.runFor(1000)}
 const stored=()=>page.evaluate(()=>Object.entries(localStorage).filter(([k])=>k.startsWith('hashpaylink:arc-trade-session:')))
 await visit('')
 await page.getByRole('button',{name:'Connect Arc wallet',exact:true}).click()
 await page.clock.runFor(1000)
 assert.equal((await stored()).length,1)
 assert.ok(!(await stored())[0][1].includes('encryptionKey'))
 await page.reload();await page.clock.runFor(1000)
 await page.getByText('Arc wallet connected',{exact:true}).waitFor()
 assert.deepEqual(await page.evaluate(()=>[window.fixture.connects,window.fixture.refreshes]),[0,1])
 await visit('&restore=outage')
 await page.getByRole('button',{name:'Retry wallet connection',exact:true}).waitFor()
 assert.equal((await stored()).length,1)
 await page.evaluate(()=>window.fixture.restoreFailure='')
 await page.getByRole('button',{name:'Retry wallet connection',exact:true}).click()
 await page.clock.runFor(1000)
 await page.getByText('Arc wallet connected',{exact:true}).waitFor()
 assert.equal(await page.evaluate(()=>window.fixture.connects),0)
 await visit('&restore=expired')
 await page.getByRole('button',{name:'Connect Arc wallet',exact:true}).waitFor()
 assert.equal((await stored()).length,0)
 await page.getByRole('button',{name:'Connect Arc wallet',exact:true}).click()
 await page.clock.runFor(1000)
 await page.getByRole('button',{name:'Switch account',exact:true}).click()
 assert.equal((await stored()).length,0)
 console.log('PASS reload restores without OTP, outage retries preserve session, expiry reconnects and account switching clears persistence')
}finally{await browser.close()}
