async page => {
  await page.goto('http://127.0.0.1:5187/pocket-gift-preview.html')
  await page.setViewportSize({width:390,height:844})
  await page.screenshot({path:'.codex-temp/gift-dark.png'})
  if(await page.evaluate(()=>getComputedStyle(document.body).backgroundColor)!=='rgb(0, 0, 0)') throw Error('Dark canvas mismatch')
  await page.getByRole('button',{name:'Redeem in Pocket'}).click()
  await page.mouse.click(5,100)
  if(await page.getByRole('dialog',{name:'Claim gift'}).count()!==1)throw Error('Backdrop dismissed claim')
  await page.getByRole('button',{name:'Claim gift',exact:true}).click()
  await page.getByRole('alert').filter({hasText:'Preview only'}).waitFor()
  await page.screenshot({path:'.codex-temp/gift-claim.png'})
  await page.getByRole('button',{name:'Close',exact:true}).click()
  await page.getByRole('button',{name:'Theme',exact:true}).click()
  await page.screenshot({path:'.codex-temp/gift-light.png'})
  for(const state of ['funding','claimed','expired','refunding','refunded']) {
    await page.getByLabel('Preview gift state').selectOption(state)
    if(await page.getByRole('button',{name:'Redeem in Pocket'}).count())throw Error('Terminal gift is redeemable')
  }
  await page.getByRole('button',{name:'Create gift',exact:true}).click()
  if(!await page.getByRole('button',{name:'Continue',exact:true}).isDisabled())throw Error('Empty gift amount must disable Continue')
  await page.getByLabel('Gift amount',{exact:true}).fill('100')
  await page.getByLabel('Gift message',{exact:true}).fill('Happy birthday!')
  await page.setViewportSize({width:320,height:640})
  if(await page.evaluate(()=>document.documentElement.scrollWidth>window.innerWidth)) throw Error('Horizontal overflow')
  await page.screenshot({path:'.codex-temp/gift-create-light.png',fullPage:true})
  await page.getByRole('button',{name:'Continue',exact:true}).click()
  await page.getByText('100 USDC',{exact:true}).waitFor()
  await page.getByText('Happy birthday!',{exact:true}).waitFor()
  await page.getByRole('button',{name:'Theme',exact:true}).click()
  await page.setViewportSize({width:390,height:844})
  console.log('PASS dark/light gift page, no outside dismissal, no mock money success, unavailable states, validation and small-screen form.')
}
